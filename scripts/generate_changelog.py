#!/usr/bin/env python3
"""Build the repository changelog from the website's major-version pages."""
from __future__ import annotations

import argparse
from pathlib import Path
import re
from urllib.parse import urljoin, urlsplit, urlunsplit

REPO = Path(__file__).resolve().parents[1]
MAJORS = (5, 4, 3, 2, 1, 0)
SITE_URL = 'https://meerschaum.io/'


def website_link(match: re.Match[str]) -> str:
    """Make website-relative Markdown links useful from the repository root too."""
    label, target = match.groups()
    parsed = urlsplit(target)
    if parsed.scheme or target.startswith(('#', '//')):
        return match.group(0)
    resolved = urlsplit(urljoin(SITE_URL + 'changelog/', target))
    path = resolved.path
    if path.endswith('/index.md'):
        path = path[:-len('index.md')]
    elif path.endswith('.md'):
        path = path[:-3] + '/'
    return f'[{label}]({urlunsplit(resolved._replace(path=path))})'


def render_changelog(source: Path) -> str:
    """Export every major in order, refusing incomplete or mislabeled input."""
    sections = []
    for major in MAJORS:
        page = source / f'v{major}.md'
        text = page.read_text(encoding='utf-8').strip()
        title, separator, body = text.partition('\n')
        if title != f'# Meerschaum {major}' or not separator or not body.strip():
            raise ValueError(f'{page}: expected a nonempty Meerschaum {major} page')
        # Nest each complete page under its major-version heading.
        lines, in_fence = [], False
        for line in text.splitlines():
            if line.lstrip().startswith(('```', '~~~')):
                in_fence = not in_fence
            if not in_fence:
                line = re.sub(r'^(#{1,5}) ', r'#\1 ', line)
                line = re.sub(r'\[([^\]]*)\]\(([^\s)]+)\)', website_link, line)
            lines.append(line)
        nested = '\n'.join(lines)
        sections.append(nested)
    return '# Changelog\n\n<!-- Generated by scripts/generate_changelog.py. -->\n\n' + '\n\n'.join(sections) + '\n'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=REPO / 'docs/zensical/changelog')
    parser.add_argument('--output', type=Path, default=REPO / 'CHANGELOG.md')
    args = parser.parse_args()
    args.output.write_text(render_changelog(args.source), encoding='utf-8')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())

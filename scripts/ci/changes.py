def _regex(pattern: str) -> 're.Pattern[str]':
    """`**` matches across directories, `*` and `?` stay inside one path segment."""
    out = []
    i = 0
    while i < len(pattern):
        char = pattern[i]
        if pattern.startswith('**/', i):
            out.append('(?:.*/)?')
            i += 3
            continue
        if char == '*':
            if pattern.startswith('**', i):
                out.append('.*')
                i += 2
                continue
            out.append('[^/]*')
        elif char == '?':
            out.append('[^/]')
        else:
            out.append(re.escape(char))
        i += 1
    return re.compile('^' + ''.join(out) + '$')


def _matcher(patterns: Iterable[str]):
    compiled = [_regex(p) for p in patterns]
    return lambda path: any(r.match(path) for r in compiled)


_is_ignored = _matcher(IGNORED)
_rust_input = _matcher(RUST)


def _is_rust(path: str) -> bool:
    # Non-Rust test data/generators are consumed by the test/parity jobs. Keep
    # unknown crate inputs and embedded src/ assets conservative.
    fixture_data = path.startswith('crates/') and '/tests/' in path and not path.endswith(('.rs', '/Cargo.toml'))
    return _rust_input(path) and not fixture_data
_is_rust_test = _matcher(RUST + RUST_TEST_EXTRA)
_is_pytest = _matcher(PYTEST)
_is_parity = _matcher(PARITY)
_is_frontcrate = _matcher(FRONTCRATE)
_is_package = _matcher(PACKAGE)
_is_duckdb = _matcher(DUCKDB)


def everything() -> Dict[str, bool]:
    return {name: True for name in NAMES} | {'full': True}


def classify(files: Sequence[str]) -> Dict[str, bool]:
    """The job flags for a list of changed paths (repository-relative, `/` separated)."""
    result = {name: False for name in NAMES} | {'full': False}
    for raw in files:
        path = raw.strip().removeprefix('./')
        if not path:
            continue
        # `*.md` is the repository root's Markdown only: a crate's README is a packaging input.
        if _is_ignored(path):
            continue
        # Crate prose and data are packaging/parity inputs, not Rust compilation inputs.
        if path.startswith('crates/') and path.endswith(('.md', '/LICENSE', '/NOTICE')):
            result['package'] = True
            continue
        claimed = False
        for name, test in (
            ('rust', _is_rust),
            ('rust_test', _is_rust_test),
            ('pytest', _is_pytest),
            ('parity', _is_parity),
            ('frontcrate', _is_frontcrate),
            ('package', _is_package),
            ('duckdb', _is_duckdb),
        ):
            if test(path):
                result[name] = True
                claimed = True
        if not claimed:
            result['rust'] = result['rust_test'] = result['pytest'] = True
    return result


def changed_files(before: str, after: str) -> List[str]:
    """`git diff --name-only before after`, fetching `before` first when the clone is shallow."""
    if not before or set(before) == {'0'}:
        raise ValueError('no base commit')
    probe = subprocess.run(['git', 'cat-file', '-e', f'{before}^{{commit}}'], capture_output=True)
    if probe.returncode != 0:
        subprocess.run(
            ['git', 'fetch', '--no-tags', '--depth=1', 'origin', before],
            check=True, capture_output=True,
        )
    out = subprocess.run(
        ['git', 'diff', '--name-only', before, after],
        check=True, capture_output=True, text=True,
    ).stdout
    return [line for line in out.splitlines() if line.strip()]


def main(argv: Sequence[str] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[1])
    parser.add_argument('--event', default=os.environ.get('GITHUB_EVENT_NAME', ''))
    parser.add_argument('--ref', default=os.environ.get('GITHUB_REF', ''))
    parser.add_argument('--before', default='', help='push: the commit before the push')
    parser.add_argument('--after', default='HEAD')
    parser.add_argument('--base', default='', help='pull_request: the base commit')
    parser.add_argument('--files', default='', help='read the changed paths from this file (`-`: stdin)')
    args = parser.parse_args(argv)

    full_event = (
        args.event in ('workflow_dispatch', 'schedule', 'workflow_call', 'release')
        or args.ref.startswith('refs/tags/')
    )
    if full_event:
        flags = everything()
    else:
        try:
            if args.files:
                text = sys.stdin.read() if args.files == '-' else open(args.files, encoding='utf-8').read()
                files = text.splitlines()
            elif args.event == 'pull_request':
                files = changed_files(args.base, args.after)
            else:
                files = changed_files(args.before, args.after)
            flags = classify(files)
            print(f'{len(files)} changed file(s)', file=sys.stderr)
        except (ValueError, subprocess.CalledProcessError, OSError) as exc:
            print(f'changes.py: cannot tell what changed ({exc}); running everything.', file=sys.stderr)
            flags = everything()

    lines = [f'{name}={"true" if flags[name] else "false"}' for name in (*NAMES, 'full')]
    print('\n'.join(lines))
    output = os.environ.get('GITHUB_OUTPUT')
    if output:
        with open(output, 'a', encoding='utf-8') as handle:
            handle.write('\n'.join(lines) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())

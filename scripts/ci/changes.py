#!/usr/bin/env python3
"""
Decide which CI jobs a change needs (used by the `changes` job of rust.yaml and pytest.yaml).

    python scripts/ci/changes.py --event push --before <sha> --after <sha>
    python scripts/ci/changes.py --event pull_request --base <sha>
    git diff --name-only A B | python scripts/ci/changes.py --event push --files -

Prints `name=true|false` lines (and appends them to `$GITHUB_OUTPUT` when set):

    rust        fmt, clippy and the hosted `cargo check` legs
    rust_test   the self-hosted `cargo nextest` job (also reads a few Python files and imports `meerschaum`)
    pytest      the Python suite (it builds the `_core` extension, so every Rust change runs it)
    parity      regenerate the v4.1.4 fixtures: only the generators, the fixtures and the reference harness
    frontcrate  the `meerschaum` front crate's feature matrix
    package     the crates.io packaging dry-run
    duckdb      the DuckDB loader on the other platforms
    full        a dispatch, a tag or a schedule: every job runs

Rules, in one place:

* A dispatch, a tag, a schedule or an unknown diff (no base commit, an error) turns everything on.
* Files that no job reads (documentation, release notes, agent notes, benchmark results) turn nothing
  on: a docs-only push runs no heavy job.
* Every other file turns on the jobs whose input it is (the tables below); a file no table claims is an
  unknown input and turns on `rust`, `rust_test` and `pytest` (the safe default).

Keep the tables in step with the workflows: tests/test_ci_changes.py pins the important cases.
"""


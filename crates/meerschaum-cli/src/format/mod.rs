/// The `ANSI` / `UNICODE` settings and the terminal geometry.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FormatSettings {
    /// `formatting:ansi`.
    pub ansi: bool,
    /// `formatting:unicode`.
    pub unicode: bool,
    /// The rich console width.
    pub width: usize,
    /// `get_cols_lines()[0]` (used by `print_options`).
    pub cols: usize,
    /// `NO_COLOR` is set.
    pub no_color: bool,
}

/// `os.get_terminal_size(fd)` for stdin (0), stdout (1) or stderr (2).
pub fn terminal_width(fd: i32) -> Option<usize> {
    let size = match fd {
        0 => terminal_size::terminal_size_of(std::io::stdin()),
        1 => terminal_size::terminal_size_of(std::io::stdout()),
        _ => terminal_size::terminal_size_of(std::io::stderr()),
    };
    size.map(|(w, _)| w.0 as usize).filter(|w| *w > 0)
}

/// rich's `Console.size.width` for `Console(force_terminal=True)`: `$COLUMNS` if it is all
/// digits, else the terminal size of stdin, stdout or stderr, else 80 (also 80 for a dumb
/// terminal).
pub fn console_width(
    env: impl Fn(&str) -> Option<String>,
    terminal: impl Fn(i32) -> Option<usize>,
) -> usize {
    if matches!(
        env("TERM").map(|t| t.to_lowercase()).as_deref(),
        Some("dumb" | "unknown")
    ) {
        return 80;
    }
    let mut width = [0, 1, 2].iter().find_map(|fd| terminal(*fd));
    if let Some(columns) = env("COLUMNS")
        && !columns.is_empty()
        && columns.chars().all(|c| c.is_ascii_digit())
    {
        width = columns.parse().ok();
    }
    match width {
        Some(w) if w > 0 => w,
        _ => 80,
    }
}

/// `get_cols_lines()[0]`: the terminal of stdout, else `$COLUMNS`, else 100.
pub fn cols_lines_width(
    env: impl Fn(&str) -> Option<String>,
    terminal: impl Fn(i32) -> Option<usize>,
) -> usize {
    terminal(1)
        .or_else(|| env("COLUMNS").and_then(|c| c.trim().parse().ok()))
        .unwrap_or(100)
}

impl FormatSettings {
    /// Settings from the config registry and the process environment.
    pub fn detect(config: &Config, env: impl Fn(&str) -> Option<String> + Copy) -> FormatSettings {
        let flag = |key: &str, default: bool| {
            config
                .get(&["formatting", key])
                .map(|v| v.truthy())
                .unwrap_or(default)
        };
        FormatSettings {
            ansi: flag("ansi", true),
            unicode: flag("unicode", !cfg!(windows)),
            width: console_width(env, terminal_width),
            cols: cols_lines_width(env, terminal_width),
            no_color: env("NO_COLOR").is_some_and(|v| !v.is_empty()),
        }
    }
}

/// Pipes grouped as `{connector: {metric: [pipes]}}` (in insertion order).
type ConnectorGroup = (String, Vec<(String, Vec<PipeKeys>)>);

/// A pipe's keys, as `pipe_repr` reads them.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PipeKeys {
    /// `connector_keys`.
    pub connector: String,
    /// `metric_key`.
    pub metric: String,
    /// `location_key`.
    pub location: Option<String>,
    /// `instance_keys` (`None`: the configured default instance).
    pub instance: Option<String>,
}

impl PipeKeys {
    /// Keys without a location or instance.
    pub fn new(connector: &str, metric: &str) -> PipeKeys {
        PipeKeys {
            connector: connector.into(),
            metric: metric.into(),
            location: None,
            instance: None,
        }
    }
}


//! The Rust CLI's formatting toolkit: a port of the parts of `meerschaum/utils/formatting/`
//! (and `meerschaum.utils.warnings.info` / `warn`) that the core actions use.
//!
//! v4 renders through `rich` on a forced truecolor console (`get_console()`), `pprintpp` when ANSI
//! is disabled, and `tabulate` for DataFrames. [`rich`] is a byte-compatible port of the rich
//! pieces involved (styles, `Text` wrapping, `Table`, `Panel`, `Tree`, `Columns`, `Pretty` and
//! `ReprHighlighter`); [`pprintpp`] and [`tabulate`] port the other two. The output of every
//! public function here is checked byte for byte against v4 by `tests/format.rs` (fixture
//! `tests/fixtures/format.json`, generated by `gen_format.py`).
//!
//! `ANSI` / `UNICODE` come from the `formatting:ansi` / `formatting:unicode` config keys; the
//! console width follows rich (`$COLUMNS`, else the terminal of stdin/stdout/stderr, else 80) and
//! `print_options` column fitting follows `get_cols_lines` (the terminal of stdout, else
//! `$COLUMNS`, else 100).


/// The formatting functions, bound to settings and the config registry.
pub struct Formatter<'c> {
    /// The settings.
    pub settings: FormatSettings,
    config: &'c Config,
    console: Console,
    formatting: Map,
    default_instance: String,
}

fn get_path<'v>(map: &'v Map, keys: &[&str]) -> Option<&'v Value> {
    let (first, rest) = keys.split_first()?;
    let mut v = map.get(*first)?;
    for k in rest {
        v = v.get(k)?;
    }
    Some(v)
}

fn get_str(map: &Map, keys: &[&str]) -> String {
    match get_path(map, keys) {
        Some(Value::Str(s)) => s.clone(),
        Some(Value::Null) | None => String::new(),
        Some(v) => v.py_str(),
    }
}

impl<'c> Formatter<'c> {
    /// A formatter over a config registry.
    pub fn new(settings: FormatSettings, config: &'c Config) -> Formatter<'c> {
        let formatting = config
            .get(&["formatting"])
            .and_then(|v| v.as_map().cloned())
            .unwrap_or_default();
        let default_instance = config
            .get(&["meerschaum", "instance"])
            .map(|v| v.py_str())
            .unwrap_or_else(|| "sql:main".into());
        let mut console = Console::new(settings.width);
        console.no_color = settings.no_color;
        Formatter {
            settings,
            config,
            console,
            formatting,
            default_instance,
        }
    }

    /// The config registry.
    pub fn config(&self) -> &Config {
        self.config
    }

    /// The rich console (`get_console()`).
    pub fn console(&self) -> &Console {
        &self.console
    }

    /// `CHARSET`.
    pub fn charset(&self) -> &'static str {
        if self.settings.unicode {
            "unicode"
        } else {
            "ascii"
        }
    }

    /// `get_config('formatting', *keys)` as a string.
    pub fn formatting_str(&self, keys: &[&str]) -> String {
        get_str(&self.formatting, keys)
    }

    /// The configured default instance (`meerschaum:instance`).
    pub fn default_instance(&self) -> &str {
        &self.default_instance
    }

    /// `colored(text, style=style)`: render through the console (wrapping at its width).
    pub fn colored(&self, text: &str, style: &str) -> String {
        self.console.text_to_str(&Text::new(text, style))
    }

    /// `rich_text_to_str(text)`.
    pub fn text_to_str(&self, text: &Text) -> String {
        self.console.text_to_str(text)
    }

    /// `fill_ansi(string, style)`: style the segments that have no style yet.
    pub fn fill_ansi(&self, string: &str, style: &str) -> String {
        let mut msg = Text::from_ansi(string, "");
        let length = msg.len();
        let mut plain: Vec<(usize, usize)> = Vec::new();
        // PARITY: `iterate_chunks(msg.spans, 2)` only looks at the gap inside each pair of spans.
        let spans = msg.spans.clone();
        for pair in spans.chunks(2) {
            let left = pair[0].end;
            let right = pair.get(1).map(|s| s.start).unwrap_or(length);
            if left != right {
                plain.push((left, right));
            }
        }
        if let (Some(first), Some(last)) = (spans.first(), spans.last()) {
            if first.start != 0 {
                plain.insert(0, (0, first.start));
            }
            if !plain.is_empty() && last.end != length && plain.last().map(|p| p.1) != Some(length)
            {
                plain.push((last.end, length));
            }
        }
        if !plain.is_empty() {
            for (left, right) in plain {
                msg.stylize(style, left, Some(right));
            }
        } else {
            msg = Text::new(&msg.plain(), style);
        }
        self.console.text_to_str(&msg)
    }

    /// `pipe_repr(pipe, as_rich_text=True)`.
    pub fn pipe_repr_text(&self, pipe: &PipeKeys) -> Text {
        self.pipe_repr_text_with(pipe, true)
    }

    /// `pipe_repr(pipe, as_rich_text=True, ansi=ansi)`.
    pub fn pipe_repr_text_with(&self, pipe: &PipeKeys, ansi: bool) -> Text {
        let style = |key: &str| -> String {
            if self.settings.ansi && ansi {
                self.formatting_str(&["pipes", "__repr__", "ansi", "styles", key])
            } else {
                String::new()
            }
        };
        let pipe_style = style("Pipe");
        let markup = |s: &str| {
            if pipe_style.is_empty() {
                Text::plain_text(s)
            } else {
                let mut t = Text::plain_text(s);
                t.stylize(pipe_style.as_str(), 0, None);
                t
            }
        };
        let colored = |s: &str, st: &str| Text::new(s, st);
        let instance = pipe
            .instance
            .clone()
            .unwrap_or_else(|| self.default_instance.clone());
        let mut text = markup("Pipe(");
        text.append_text(&colored(
            &format!("'{}'", pipe.connector),
            &style("connector"),
        ));
        text.append_text(&markup(", "));
        text.append_text(&colored(&format!("'{}'", pipe.metric), &style("metric")));
        if let Some(loc) = &pipe.location {
            text.append_text(&colored(", ", &style("punctuation")));
            text.append_text(&colored(&format!("'{loc}'"), &style("location")));
        }
        if instance != self.default_instance {
            text.append_text(&colored(", instance=", &style("punctuation")));
            text.append_text(&colored(&format!("'{instance}'"), &style("instance")));
        }
        text.append_text(&markup(")"));
        text
    }

    /// `pipe_repr(pipe)`.
    pub fn pipe_repr(&self, pipe: &PipeKeys) -> String {
        self.text_to_str(&self.pipe_repr_text(pipe))
            .replace('\n', "")
    }

    /// `highlight_pipes(message)`.
    pub fn highlight_pipes(&self, message: &str) -> String {
        if !message.contains("Pipe(") {
            return message.to_string();
        }
        let mut msg = String::new();
        for (i, segment) in message.split("Pipe(").enumerate() {
            if i == 0 {
                msg.push_str(segment);
                continue;
            }
            let Some(paren) = segment.find(')') else {
                msg.push_str("Pipe(");
                msg.push_str(segment);
                continue;
            };
            let args_str = &segment[..paren];
            match self.parse_pipe_args(args_str) {
                Some(keys) => {
                    msg.push_str(&self.pipe_repr(&keys));
                    msg.push_str(&segment[paren + 1..]);
                }
                None => {
                    msg.push_str("Pipe(");
                    msg.push_str(segment);
                }
            }
        }
        msg
    }

    fn parse_pipe_args(&self, args_str: &str) -> Option<PipeKeys> {
        let (args, kwargs) = parse_arguments_str(args_str).ok()?;
        let as_str = |v: &Value| match v {
            Value::Str(s) => Some(s.clone()),
            _ => None,
        };
        let connector = as_str(args.first()?)?;
        let metric = as_str(args.get(1)?)?;
        let location = match args.get(2) {
            None | Some(Value::Null) => None,
            Some(v) => Some(as_str(v)?),
        };
        let instance = match kwargs.get("instance") {
            None => None,
            Some(v) => Some(as_str(v)?),
        };
        Some(PipeKeys {
            connector,
            metric,
            location,
            instance,
        })
    }

    /// `format_success_tuple(tup, upper_padding, lower_padding, left_padding, calm)`.
    pub fn format_success_tuple(
        &self,
        tup: &SuccessTuple,
        upper_padding: usize,
        lower_padding: usize,
        left_padding: usize,
        calm: bool,
    ) -> String {
        let mut status = if tup.success { "success" } else { "failure" }.to_string();
        if calm {
            status.push_str("_calm");
        }
        let icon = self.formatting_str(&[&status, self.charset(), "icon"]);
        let msg = format!(
            "{}{icon} {}",
            " ".repeat(left_padding),
            self.highlight_pipes(&tup.message)
        );
        let mut lines: Vec<String> = msg.split('\n').map(str::to_string).collect();
        for line in lines.iter_mut().skip(1) {
            if !line.starts_with(' ') {
                *line = format!("    {line}");
            }
        }
        if self.settings.ansi {
            let style = self.formatting_str(&[&status, "ansi", "rich", "style"]);
            lines[0] = self.fill_ansi(&lines[0], &style);
        }
        format!(
            "{}{}{}",
            "\n".repeat(upper_padding),
            lines.join("\n"),
            "\n".repeat(lower_padding)
        )
    }

    /// `print_tuple(tup, ...)`: the printed text (empty when skipped).
    pub fn print_tuple(&self, tup: &SuccessTuple, args: TupleArgs) -> String {
        let ignored = static_config()
            .system
            .success
            .ignore
            .iter()
            .any(|m| m.as_deref() == Some(py_strip(&tup.message)));
        let mut skip_common = args.skip_common;
        let mut do_print = true;
        if args.common_only {
            skip_common = false;
            do_print = ignored;
        }
        if skip_common {
            do_print = !ignored;
        }
        if !do_print {
            return String::new();
        }
        format!(
            "{}\n",
            self.format_success_tuple(tup, args.upper_padding, args.lower_padding, 1, args.calm)
        )
    }

    /// `make_header(message, ruler, left_pad, top, top_pad)`.
    pub fn make_header_with(
        &self,
        message: &str,
        ruler: &str,
        left_pad: usize,
        top: bool,
        top_pad: usize,
    ) -> String {
        let ruler = if self.settings.unicode { ruler } else { "-" };
        let max_length = message
            .split('\n')
            .map(|w| w.chars().count())
            .max()
            .unwrap_or(0);
        let left = " ".repeat(left_pad);
        let rule = ruler.repeat(max_length);
        format!(
            "{}{left}{}{}\n{left}{rule}",
            if top {
                "\n".repeat(top_pad)
            } else {
                String::new()
            },
            if top {
                format!("{rule}\n")
            } else {
                String::new()
            },
            message.replace('\n', &format!("\n{left}")),
        )
    }

    /// `make_header(message)`.
    pub fn make_header(&self, message: &str) -> String {
        self.make_header_with(message, "─", 2, false, 1)
    }

    /// `print_options(options, ...)`: the printed text.
    pub fn print_options(&self, options: &[String], args: &OptionsArgs) -> String {
        let mut options: Vec<String> = options.to_vec();
        if args.sort_options {
            options.sort();
        }
        let header = args
            .header
            .clone()
            .unwrap_or_else(|| format!("\nAvailable {}", args.name));
        let mut num_cols = args.num_cols.unwrap_or(8);

        if args.nopretty {
            let mut out = String::new();
            for option in &options {
                out.push_str(option);
                out.push('\n');
            }
            return out;
        }

        if args.adjust_cols && !options.is_empty() {
            let cols = self.settings.cols as i64;
            while num_cols > 1 {
                let n = num_cols as i64;
                // `int(x / y)` truncates toward zero.
                let cell_len = (((cols - 4) - 3 * (n - 1)) as f64 / n as f64).trunc() as i64;
                let too_big = options
                    .iter()
                    .filter(|o| string_width(o) as i64 > cell_len)
                    .count();
                if too_big > options.len() / 3 {
                    num_cols -= 1;
                    continue;
                }
                break;
            }
        }

        let mut table = Table::new();
        table.title = Some(Text::new(&header, ""));
        table.box_chars = Some(SIMPLE);
        table.show_header = false;
        table.expand = true;
        for _ in 0..num_cols {
            table.add_column(Column::default());
        }
        let item = |i: usize, option: &str| -> Box<dyn Renderable> {
            let mut item = self.highlight_pipes(option);
            if args.number_options {
                item = format!("{}. {item}", i + 1);
            }
            Box::new(Text::from_ansi(&item, ""))
        };
        if options.len() < 12 {
            for (i, option) in options.iter().enumerate() {
                table.add_row(vec![Some(item(i, option))]);
            }
        } else {
            let num_rows = options.len().div_ceil(num_cols);
            for i in 0..num_rows {
                let mut row: Vec<Option<Box<dyn Renderable>>> = Vec::new();
                for j in 0..num_cols {
                    let index = i + j * num_rows;
                    if index < options.len() {
                        // PARITY: numbered multi-column options use the row number (`i + 1`).
                        row.push(Some(item(i, &options[index])));
                    } else {
                        row.push(Some(Box::new(Text::plain_text(""))));
                    }
                }
                table.add_row(row);
            }
        }
        self.console.print(&table)
    }

    /// `print_options` without rich (`nopretty=False, no_rich=True`): the header and a bullet
    /// list.
    pub fn print_options_plain(&self, options: &[String], args: &OptionsArgs) -> String {
        let header = args
            .header
            .clone()
            .unwrap_or_else(|| format!("\nAvailable {}", args.name));
        let mut out = format!("\n{}\n", self.make_header(&header));
        for (i, option) in options.iter().enumerate() {
            let marker = if args.number_options {
                format!("{}.", i + 1)
            } else {
                "-".into()
            };
            out.push_str(&format!("  {marker} {option}\n"));
        }
        out.push('\n');
        out
    }

    /// `pprint(obj, nopretty=...)`: the printed text.
    pub fn pprint(&self, obj: &PyObj, nopretty: bool) -> String {
        if let PyObj::Tuple(items) = obj
            && items.len() == 2
            && let (PyObj::Bool(success), PyObj::Str(message)) = (&items[0], &items[1])
        {
            return self.print_tuple(
                &SuccessTuple {
                    success: *success,
                    message: message.clone(),
                },
                TupleArgs::default(),
            );
        }
        let obj = match obj {
            PyObj::Dict(_) => replace_password(obj),
            other => other.clone(),
        };
        if nopretty {
            let text = match obj.to_value() {
                Some(v) => json_dumps(&v, JsonStyle::Default, true),
                None => obj.py_str(),
            };
            return format!("{text}\n");
        }
        if self.settings.ansi {
            match &obj {
                PyObj::Dict(_) | PyObj::List(_) | PyObj::Tuple(_) | PyObj::Set(_) => {
                    self.console.print(&Pretty {
                        obj: &obj,
                        highlight: true,
                    })
                }
                other => {
                    // `console.print(obj)` highlights `str(obj)` with `ReprHighlighter`.
                    let mut t = Text::plain_text(&other.py_str());
                    rich::pretty::highlight_repr(&mut t);
                    self.console.print_text(&t)
                }
            }
        } else {
            pprintpp::pprint(&obj, 4, 80)
        }
    }

    /// `pprint_pipes(pipes)`: the pipes tree by connector, metric and location.
    pub fn pprint_pipes(&self, pipes: &[PipeKeys]) -> String {
        // Group as `{connector: {metric: {location: pipe}}}` in insertion order.
        let mut grouped: Vec<ConnectorGroup> = Vec::new();
        for p in pipes {
            let ci = match grouped.iter().position(|(c, _)| *c == p.connector) {
                Some(i) => i,
                None => {
                    grouped.push((p.connector.clone(), Vec::new()));
                    grouped.len() - 1
                }
            };
            let metrics = &mut grouped[ci].1;
            let mi = match metrics.iter().position(|(m, _)| *m == p.metric) {
                Some(i) => i,
                None => {
                    metrics.push((p.metric.clone(), Vec::new()));
                    metrics.len() - 1
                }
            };
            let locations = &mut metrics[mi].1;
            match locations.iter().position(|l| l.location == p.location) {
                Some(i) => locations[i] = p.clone(),
                None => locations.push(p.clone()),
            }
        }
        let icon = |k: &str| self.formatting_str(&["pipes", self.charset(), "icons", k]);
        let style = |k: &str| {
            if self.settings.ansi {
                self.formatting_str(&["pipes", "ansi", "styles", k])
            } else {
                String::new()
            }
        };
        let mut out = String::from("\n");
        if !self.settings.unicode {
            out.push_str(&self.ascii_pipes(&grouped, &icon, &style));
            return out;
        }
        // PARITY: `sorted_dict(pipes)` sorts by the values (dicts), which raises TypeError for
        // two or more connectors and returns the dictionary unchanged (`utils/misc.py:426`).
        let mut key = Text::plain_text("\n");
        key.append_text(&Text::new(
            &format!("{}Connector", icon("connector")),
            style("connector"),
        ));
        key.append_text(&Text::plain_text("\n\n"));
        key.append_text(&Text::new(
            &format!("{}Metric", icon("metric")),
            style("metric"),
        ));
        key.append_text(&Text::plain_text("\n\n"));
        key.append_text(&Text::new(
            &format!("{}Location", icon("location")),
            style("location"),
        ));
        key.append_text(&Text::plain_text("\n"));
        let mut panel = Panel::new(Box::new(key));
        panel.title = Some(Text::new(&format!("{}Keys", icon("key")), style("guide")));
        panel.border_style = StyleRef::Name(style("guide"));
        panel.expand = true;

        let mut cols: Vec<Box<dyn Renderable>> = vec![Box::new(panel)];
        for (conn, metrics) in &grouped {
            let mut conn_tree = Tree::new(
                Box::new(Text::new(
                    &format!("{}{conn}", icon("connector")),
                    style("connector"),
                )),
                style("connector"),
            );
            for (metric, locations) in metrics {
                let mut metric_tree = Tree::new(
                    Box::new(Text::new(
                        &format!("{}{metric}", icon("metric")),
                        style("metric"),
                    )),
                    style("metric"),
                );
                for pipe in locations {
                    let loc = match &pipe.location {
                        None => Text::new("None", style("none")),
                        Some(l) => Text::new(l, style("location")),
                    };
                    let mut label = Text::plain_text(&icon("location"));
                    label.append_text(&loc);
                    label.append_text(&Text::plain_text("\n"));
                    label.append_text(&self.pipe_repr_text(pipe));
                    label.append_text(&Text::plain_text("\n"));
                    metric_tree.add(Box::new(label));
                }
                conn_tree.add(Box::new(metric_tree));
            }
            cols.push(Box::new(conn_tree));
        }
        out.push_str(&self.console.print(&Columns {
            renderables: cols,
            equal: false,
        }));
        out
    }

    fn ascii_pipes(
        &self,
        grouped: &[ConnectorGroup],
        icon: &dyn Fn(&str) -> String,
        style: &dyn Fn(&str) -> String,
    ) -> String {
        // `asciitree.LeftAligned()` over `{connector: {metric: {location + repr: {}}}}`.
        fn child(lines: &mut Vec<String>, label_lines: Vec<String>, last: bool) {
            for (i, l) in label_lines.into_iter().enumerate() {
                let prefix = match (i, last) {
                    (0, _) => " +-- ",
                    (_, false) => " |  ",
                    (_, true) => "    ",
                };
                lines.push(format!("{prefix}{l}"));
            }
        }
        let mut cols: Vec<Text> = Vec::new();
        let mut key = Text::plain_text("     ");
        key.append_text(&Text::new("Key", "underline"));
        key.append_text(&Text::plain_text("\n\n  "));
        key.append_text(&Text::new("Connector", style("connector")));
        key.append_text(&Text::plain_text("\n   +-- "));
        key.append_text(&Text::new("Metric", style("metric")));
        key.append_text(&Text::plain_text("\n       +-- "));
        key.append_text(&Text::new("Location", style("location")));
        key.append_text(&Text::plain_text("\n\n"));
        cols.push(key);
        for (conn, metrics) in grouped {
            let conn_label =
                self.colored(&format!("{}{conn}", icon("connector")), &style("connector"));
            let mut replace: Vec<(String, Text)> =
                vec![(conn_label.clone(), Text::new(conn, style("connector")))];
            let mut lines = vec![conn_label];
            for (mi, (metric, locations)) in metrics.iter().enumerate() {
                let metric_label =
                    self.colored(&format!("{}{metric}", icon("metric")), &style("metric"));
                replace.push((metric_label.clone(), Text::new(metric, style("metric"))));
                let mut metric_lines = vec![metric_label];
                for (li, pipe) in locations.iter().enumerate() {
                    let loc_style = if pipe.location.is_none() {
                        style("none")
                    } else {
                        style("location")
                    };
                    let loc = pipe.location.clone().unwrap_or_else(|| "None".into());
                    let colored_loc =
                        self.colored(&format!("{}{loc}", icon("location")), &loc_style);
                    replace.push((colored_loc.clone(), Text::new(&loc, loc_style.as_str())));
                    // `pipe.__repr__()` is plain outside an interactive interpreter.
                    let repr = self
                        .text_to_str(&self.pipe_repr_text_with(pipe, false))
                        .replace('\n', "");
                    let label = format!("{colored_loc}\n         {repr}\n");
                    let label_lines: Vec<String> = vec![label];
                    child(&mut metric_lines, label_lines, li + 1 == locations.len());
                }
                child(&mut lines, metric_lines, mi + 1 == metrics.len());
            }
            let tree = lines.join("\n");
            let col = if !self.settings.unicode && !self.settings.ansi {
                Text::plain_text(&tree)
            } else {
                replace_tree_text(&tree, &replace)
            };
            cols.push(col);
        }
        let renderables: Vec<Box<dyn Renderable>> = cols
            .into_iter()
            .map(|t| Box::new(t) as Box<dyn Renderable>)
            .collect();
        self.console.print(&Columns {
            renderables,
            equal: false,
        })
    }

    /// `info(message, icon=True)`: the printed text.
    pub fn info(&self, message: &str, icon: bool) -> String {
        let mut message = message.to_string();
        if icon {
            message = format!(
                " {} {message}",
                self.formatting_str(&["info", self.charset(), "icon"])
            );
        }
        if self.settings.ansi {
            message = self.highlight_pipes(&message);
            let style = self.formatting_str(&["info", "ansi", "rich", "style"]);
            let lines: Vec<&str> = message.split('\n').collect();
            let mut out = self.fill_ansi(lines[0], &style);
            if lines.len() > 1 {
                out.push('\n');
                out.push_str(&lines[1..].join("\n"));
            }
            message = out;
        }
        format!("{message}\n")
    }

    /// `warn(message, stack=False)`: the text written to stderr.
    pub fn warn(&self, message: &str) -> String {
        let icon = self.formatting_str(&["warnings", self.charset(), "icon"]);
        let mut msg = format!(" {icon} {message}");
        if self.settings.ansi {
            let style = self.formatting_str(&["warnings", "ansi", "rich", "style"]);
            msg = self.fill_ansi(&self.highlight_pipes(&msg), &style);
        }
        format!("{msg}\n")
    }
}

/// `replace_tree_text`: swap each colored label in the tree for a styled `Text`.
fn replace_tree_text(tree: &str, replace: &[(String, Text)]) -> Text {
    let mut tree_text = Text::plain_text(tree);
    for (colored, text) in replace {
        let lines = tree_text.split_str(colored, false);
        let mut parts: Vec<Text> = Vec::new();
        for part in &lines {
            parts.push(part.clone());
            parts.push(text.clone());
        }
        let last_is_blank = lines
            .last()
            .is_some_and(|l| l.is_empty() && l.spans.is_empty());
        if !last_is_blank {
            parts.pop();
        }
        let mut joined = Text::plain_text("");
        for part in &parts {
            joined = joined.plus(part);
        }
        tree_text = joined;
    }
    tree_text
}

/// `string_width(string)`: the longest line, in code points.
pub fn string_width(s: &str) -> usize {
    s.split('\n').map(|w| w.chars().count()).max().unwrap_or(0)
}

/// `replace_password(d)`: mask `password` values and the password inside `uri` values.
pub fn replace_password(obj: &PyObj) -> PyObj {
    let PyObj::Dict(items) = obj else {
        return obj.clone();
    };
    PyObj::Dict(
        items
            .iter()
            .map(|(k, v)| {
                let key = k.py_str();
                let new = if let PyObj::Dict(_) = v {
                    replace_password(v)
                } else if key.to_lowercase().contains("password") {
                    PyObj::Str("*".repeat(v.py_str().chars().count()))
                } else if key.to_lowercase() == "uri" {
                    match v {
                        PyObj::Str(uri) => match uri_user_password(uri) {
                            Some((user, password)) => PyObj::Str(uri.replace(
                                &format!("{user}:{password}"),
                                &format!("{user}:{}", "*".repeat(password.chars().count())),
                            )),
                            None => v.clone(),
                        },
                        _ => v.clone(),
                    }
                } else {
                    v.clone()
                };
                (k.clone(), new)
            })
            .collect(),
    )
}

/// The username and password of a SQLAlchemy URL (`make_url(uri)`), if both are present.
fn uri_user_password(uri: &str) -> Option<(String, String)> {
    let (scheme, rest) = uri.split_once("://")?;
    if scheme.is_empty()
        || !scheme
            .chars()
            .all(|c| c.is_alphanumeric() || c == '_' || c == '+')
    {
        return None;
    }
    let at = rest.rfind('@')?;
    let userinfo = &rest[..at];
    let (user, password) = userinfo.split_once(':')?;
    if user.contains('/') {
        return None;
    }
    let decode = |s: &str| percent_decode(s);
    Some((decode(user), decode(password)))
}

fn percent_decode(s: &str) -> String {
    let bytes = s.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%'
            && i + 2 < bytes.len()
            && let Ok(b) = u8::from_str_radix(&s[i + 1..i + 3], 16)
        {
            out.push(b);
            i += 3;
            continue;
        }
        out.push(bytes[i]);
        i += 1;
    }
    String::from_utf8_lossy(&out).into_owned()
}

/// Strip SGR sequences (`remove_ansi`).
pub fn remove_ansi(s: &str) -> String {
    static RE: std::sync::LazyLock<regex::Regex> =
        std::sync::LazyLock::new(|| regex::Regex::new(r"\x1b\[[0-9;]*m").expect("regex"));
    RE.replace_all(s, "").into_owned()
}

/// A style definition is truthy (non-empty).
pub fn style_is_set(style: &str) -> bool {
    !style.is_empty()
}

/// The null style (re-exported for callers building texts).
pub fn null_style() -> Style {
    Style::null()
}

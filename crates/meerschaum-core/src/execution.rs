//! Team execution settings and the identities shared by the API, CLI and stack generator.
//!
//! Selection is explicit: a selected remote executor that cannot accept work is an error.
//! Neither health failures nor malformed settings authorize execution on the API host.
//! Credentials and private signing keys never belong in a team's readable attributes.

use std::collections::BTreeSet;
use std::net::IpAddr;

use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};

use crate::access::Team;

/// The team attribute carrying its execution settings.
pub const ATTRIBUTE: &str = "execution";
/// Bounds generated services and configuration delivery for a single team.
pub const MAX_RELAYS: usize = 64;

/// Where a team's operations run.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Mode {
    /// The existing host execution and sandbox behavior.
    #[default]
    Host,
    /// A sibling service generated by `mrsm stack`.
    Container,
    /// An independently provisioned executor, addressed by an administrator's API connector.
    Api,
}

impl Mode {
    /// Whether execution must be delegated instead of using the host.
    pub fn is_remote(self) -> bool {
        self != Self::Host
    }
}

/// A container's outbound networking policy.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Egress {
    /// HTTP(S) through a filtering proxy, plus administrator-declared destination relays.
    #[default]
    Proxy,
    /// The assigned database and authenticated main API only.
    None,
    /// An ordinary network with unrestricted outbound reach.
    Open,
}

/// Container limits. Memory has no additional swap allowance; disk is not capped here.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct Limits {
    /// Memory in MiB.
    pub memory_mb: u64,
    /// CPU quota, in CPU equivalents.
    pub cpus: f64,
    /// Maximum processes/threads in the container.
    pub pids: u32,
}

impl Default for Limits {
    fn default() -> Self {
        Self {
            memory_mb: 4096,
            cpus: 2.0,
            pids: 1024,
        }
    }
}

impl Limits {
    /// Memory in bytes, rejecting zero and overflow before emitting a Compose service.
    pub fn memory_bytes(&self) -> Result<u64, SettingsError> {
        self.memory_mb
            .checked_mul(1024 * 1024)
            .filter(|v| *v > 0)
            .ok_or_else(|| invalid("limits.memory_mb must be positive and fit in bytes"))
    }

    fn validate(&self) -> Result<(), SettingsError> {
        self.memory_bytes()?;
        if !self.cpus.is_finite() || self.cpus <= 0.0 {
            return Err(invalid("limits.cpus must be a finite positive number"));
        }
        if self.pids == 0 {
            return Err(invalid("limits.pids must be positive"));
        }
        Ok(())
    }
}

/// An explicitly permitted destination for a protocol that does not use the HTTP(S) proxy.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Relay {
    /// A hostname or an unbracketed IP address, never a URL or a shell expression.
    pub host: String,
    /// The one permitted destination port.
    pub port: u16,
}

impl Relay {
    fn normalize(&mut self) -> Result<(), SettingsError> {
        self.host = self.host.trim().trim_end_matches('.').to_ascii_lowercase();
        if self.port == 0 {
            return Err(invalid("a relay destination port must be positive"));
        }
        if let Ok(ip) = self.host.parse::<IpAddr>() {
            self.host = ip.to_string();
            return Ok(());
        }
        if self.host.len() > 253
            || self.host.split('.').any(|part| {
                part.is_empty()
                    || part.len() > 63
                    || part.starts_with('-')
                    || part.ends_with('-')
                    || !part
                        .bytes()
                        .all(|c| c.is_ascii_alphanumeric() || c == b'-' || c == b'_')
            })
        {
            return Err(invalid(
                "a relay host must be an ASCII hostname or IP address",
            ));
        }
        Ok(())
    }

    /// A stable suffix for a generated relay, independent of its position in the list.
    pub fn key(&self) -> String {
        digest(format!("{}\0{}", self.host, self.port).as_bytes())[..16].to_string()
    }
}

/// Team-readable desired settings. Control credentials are stored separately by the main API.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct Settings {
    /// Host, generated container, or an independently provisioned API.
    pub mode: Mode,
    /// Administrator-owned `api:<label>` connector, required only in API mode.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub connector: Option<String>,
    /// Outbound policy of a generated container.
    pub egress: Egress,
    /// Administrator-managed resource limits.
    pub limits: Limits,
    /// Fixed destinations for non-proxy protocols.
    pub relays: Vec<Relay>,
    /// Optional OCI runtime name (for example `runsc`).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub runtime: Option<String>,
}

/// A configuration error safe to show without printing the setting's values.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("Invalid team execution settings: {0}")]
pub struct SettingsError(String);

fn invalid(message: impl Into<String>) -> SettingsError {
    SettingsError(message.into())
}

fn digest(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

impl Settings {
    /// Read and validate one team's settings. Omission preserves existing host behavior;
    /// malformed remote settings are errors, never a request to fall back to the host.
    pub fn for_team(team: &Team) -> Result<Self, SettingsError> {
        let settings = Self::for_registration(team)?;
        if settings.mode.is_remote() {
            team_key(team)?;
        }
        Ok(settings)
    }

    /// Validate attributes before a new team has been assigned its registered UUID. Runtime
    /// selection must use [`Self::for_team`], which also requires a valid persistent identity.
    pub fn for_registration(team: &Team) -> Result<Self, SettingsError> {
        let mut settings = match team.attributes.get(ATTRIBUTE) {
            None => Self::default(),
            Some(value) => serde_json::from_value(
                serde_json::to_value(value).map_err(|_| invalid("expected an object"))?,
            )
            .map_err(|_| invalid("expected an object with valid mode, connector, egress, limits, relays and runtime fields"))?,
        };
        settings.normalize()?;
        if settings.mode.is_remote() && !team.is_isolated() {
            return Err(invalid(
                "a separate team executor requires an isolated team",
            ));
        }
        Ok(settings)
    }

    /// Validate values and canonicalize names before persistence or fingerprinting.
    pub fn normalize(&mut self) -> Result<(), SettingsError> {
        self.limits.validate()?;
        if let Some(connector) = &mut self.connector {
            *connector = connector.trim().to_string();
        }
        match (self.mode, self.connector.as_deref()) {
            (Mode::Api, Some(keys))
                if keys.strip_prefix("api:").is_some_and(|label| {
                    !label.is_empty()
                        && label.len() <= 128
                        && label
                            .bytes()
                            .all(|c| c.is_ascii_alphanumeric() || matches!(c, b'_' | b'-' | b'.'))
                }) => {}
            (Mode::Api, _) => {
                return Err(invalid(
                    "API mode requires connector keys of the form api:<label>",
                ));
            }
            (_, Some(_)) => return Err(invalid("connector is valid only in API mode")),
            (_, None) => {}
        }
        if let Some(runtime) = &mut self.runtime {
            *runtime = runtime.trim().to_string();
            if runtime.is_empty()
                || !runtime
                    .bytes()
                    .all(|c| c.is_ascii_alphanumeric() || matches!(c, b'_' | b'-' | b'.'))
            {
                return Err(invalid("runtime must be an OCI runtime name"));
            }
        }
        if self.relays.len() > MAX_RELAYS {
            return Err(invalid(format!(
                "at most {MAX_RELAYS} relay destinations are allowed"
            )));
        }
        let mut destinations = BTreeSet::new();
        for relay in &mut self.relays {
            relay.normalize()?;
            if !destinations.insert((relay.host.clone(), relay.port)) {
                return Err(invalid("relay destinations must be unique"));
            }
        }
        self.relays.sort();
        Ok(())
    }

    /// Fingerprint desired deployment settings. A changed fingerprint needs reconciliation.
    pub fn fingerprint(&self) -> Result<String, SettingsError> {
        let mut canonical = self.clone();
        canonical.normalize()?;
        let bytes = serde_json::to_vec(&canonical)
            .map_err(|_| invalid("settings cannot be represented as JSON"))?;
        Ok(digest(&bytes))
    }

    /// The connector the host uses to reach the executor. Generated connector keys never
    /// enter the team's granted connector list or its filtered plugin configuration.
    pub fn connector_keys(&self, team: &Team) -> Result<Option<String>, SettingsError> {
        match self.mode {
            Mode::Host => Ok(None),
            Mode::Container => Ok(Some(format!("api:{}", team_key(team)?))),
            Mode::Api => self
                .connector
                .clone()
                .map(Some)
                .ok_or_else(|| invalid("API mode requires an executor connector")),
        }
    }
}

/// Stable Compose service/network/volume prefix, based on the registered id, never the name.
pub fn team_key(team: &Team) -> Result<String, SettingsError> {
    let id = team
        .id
        .as_deref()
        .and_then(|id| uuid::Uuid::parse_str(id).ok())
        .ok_or_else(|| invalid("a separate executor requires a registered UUID team id"))?;
    Ok(format!("team-{}", id.simple()))
}

impl Team {
    /// Validated execution settings, without control credentials.
    pub fn execution(&self) -> Result<Settings, SettingsError> {
        Settings::for_team(self)
    }
}

/// Administrator policy, off by default. Independent APIs and generated containers share
/// the same delegation contract; their administrator provides the actual isolation boundary.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct Policy {
    /// Require a separate executor before an isolated team may install its own plugins.
    pub require_team_executor: bool,
}

/// Why dispatch is refused, distinguishing invalid configuration from an unavailable service.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum PolicyError {
    /// Invalid desired settings.
    #[error(transparent)]
    Settings(#[from] SettingsError),
    /// The administrator requires a separate executor for this team.
    #[error("This server requires a separate executor for teams that install plugins.")]
    Required,
    /// A selected executor must be provisioned and healthy before new work starts.
    #[error(
        "The selected executor is unavailable or not provisioned; an administrator must reconcile it."
    )]
    Unavailable,
}

impl Policy {
    /// Decide whether new work may start. Remote selection always fails closed when unhealthy.
    pub fn check(&self, team: &Team, ready: bool) -> Result<Settings, PolicyError> {
        let settings = team.execution()?;
        if self.require_team_executor
            && team.is_isolated()
            && team.may_write_plugins()
            && !settings.mode.is_remote()
        {
            return Err(PolicyError::Required);
        }
        if settings.mode.is_remote() && !ready {
            return Err(PolicyError::Unavailable);
        }
        Ok(settings)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Value;
    use serde_json::json;

    fn team(settings: serde_json::Value) -> Team {
        let mut team = Team::new("River");
        team.id = Some("82b340c2-0730-4ad2-91aa-f75209941399".into());
        team.attributes.insert("isolated".into(), Value::Bool(true));
        team.attributes
            .insert(ATTRIBUTE.into(), serde_json::from_value(settings).unwrap());
        team
    }

    #[test]
    fn omission_preserves_host_execution_and_resource_defaults() {
        let settings = Team::new("Legacy").execution().unwrap();
        assert_eq!(settings.mode, Mode::Host);
        assert_eq!(settings.egress, Egress::Proxy);
        assert_eq!(settings.limits, Limits::default());
        assert_eq!(
            settings.limits.memory_bytes().unwrap(),
            4 * 1024 * 1024 * 1024
        );
        assert_eq!(
            Policy::default()
                .check(&Team::new("Legacy"), false)
                .unwrap(),
            settings
        );
    }

    #[test]
    fn invalid_settings_do_not_choose_host_execution() {
        for value in [
            json!(null),
            json!("container"),
            json!({"mode":"typo"}),
            json!({"mode":"container", "memroy_mb":2}),
            json!({"mode":"container", "connector":"api:remote"}),
            json!({"mode":"api"}),
            json!({"mode":"api", "connector":"sql:main"}),
            json!({"mode":"api", "connector":"api:https://host"}),
        ] {
            assert!(team(value.clone()).execution().is_err(), "{value}");
        }
    }

    #[test]
    fn resource_limits_reject_invalid_or_overflowing_values() {
        for limits in [
            json!({"cpus":0}),
            json!({"cpus":-1}),
            json!({"memory_mb":0}),
            json!({"memory_mb":u64::MAX}),
            json!({"pids":0}),
            json!({"pids":-1}),
        ] {
            assert!(
                team(json!({"mode":"container", "limits":limits}))
                    .execution()
                    .is_err()
            );
        }
        let mut settings = Settings::default();
        settings.limits.cpus = f64::NAN;
        assert!(settings.normalize().is_err());
        settings.limits.cpus = f64::INFINITY;
        assert!(settings.normalize().is_err());
    }

    #[test]
    fn team_rename_preserves_all_generated_resource_names() {
        let mut team = team(json!({"mode":"container"}));
        let before = team.execution().unwrap().connector_keys(&team).unwrap();
        team.name = "Renamed".into();
        assert_eq!(
            team.execution().unwrap().connector_keys(&team).unwrap(),
            before
        );
        assert_eq!(
            team_key(&team).unwrap(),
            "team-82b340c207304ad291aaf75209941399"
        );
        team.id = Some("../../another-team".into());
        assert!(team.execution().is_err());
    }

    #[test]
    fn remote_execution_requires_an_isolated_registered_team() {
        let mut team = team(json!({"mode":"container"}));
        team.attributes
            .insert("isolated".into(), Value::Bool(false));
        assert!(team.execution().is_err());
        team.attributes.insert("isolated".into(), Value::Bool(true));
        team.id = None;
        assert!(team.execution().is_err());
    }

    #[test]
    fn failed_remote_health_never_falls_back_even_with_the_policy_off() {
        let team = team(json!({"mode":"container"}));
        assert!(Policy::default().check(&team, false).is_err());
        assert_eq!(
            Policy::default().check(&team, true).unwrap().mode,
            Mode::Container
        );
    }

    #[test]
    fn enforcement_policy_requires_an_executor_for_plugin_installs() {
        let mut team = team(json!({"mode":"host"}));
        team.attributes
            .insert("plugins_write".into(), Value::Bool(true));
        let policy = Policy {
            require_team_executor: true,
        };
        assert!(policy.check(&team, true).is_err());
        team.attributes.insert(
            ATTRIBUTE.into(),
            serde_json::from_value(json!({"mode":"api", "connector":"api:remote"})).unwrap(),
        );
        assert!(policy.check(&team, false).is_err());
        assert_eq!(
            policy
                .check(&team, true)
                .unwrap()
                .connector_keys(&team)
                .unwrap(),
            Some("api:remote".into())
        );
    }

    #[test]
    fn relay_destinations_are_normalized_and_fingerprints_ignore_order() {
        let a = team(json!({"mode":"container", "relays":[{"host":"DB.EXAMPLE.","port":5432},{"host":"2001:4860:4860::8888","port":443}]})).execution().unwrap();
        let b = team(json!({"mode":"container", "relays":[{"host":"2001:4860:4860::8888","port":443},{"host":"db.example","port":5432}]})).execution().unwrap();
        assert_eq!(a, b);
        assert_eq!(a.fingerprint().unwrap(), b.fingerprint().unwrap());
        let mut changed = b.clone();
        changed.limits.memory_mb += 1;
        assert_ne!(a.fingerprint().unwrap(), changed.fingerprint().unwrap());
    }

    #[test]
    fn malformed_or_duplicate_relays_are_refused() {
        for host in [
            "",
            "https://example.com",
            "user@example.com",
            "x;command",
            "x/y",
            "-host",
            "x..y",
        ] {
            assert!(
                team(json!({"mode":"container", "relays":[{"host":host,"port":443}]}))
                    .execution()
                    .is_err(),
                "{host}"
            );
        }
        assert!(
            team(json!({"mode":"container", "relays":[{"host":"a.example","port":0}]}))
                .execution()
                .is_err()
        );
        assert!(team(json!({"mode":"container", "relays":[{"host":"A.EXAMPLE.","port":443},{"host":"a.example","port":443}]})).execution().is_err());
    }
}
